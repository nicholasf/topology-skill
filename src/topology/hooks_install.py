#!/usr/bin/env python3
"""
hooks_install.py — install, remove and report the topology hooks for each
agent harness.

Invoked via:
  topology hooks install   --target claude|pi|goose [--scope user|project]
  topology hooks uninstall --target claude|pi|goose [--scope user|project]
  topology hooks status    [--scope user|project]

claude  Adds SessionStart and UserPromptSubmit entries to settings.json that
        call `topology hook ... --format claude`. Entries are recognised by
        the HOOK_MARKER substring, so install is idempotent and uninstall
        removes only ours. The previous file is copied to
        settings.json.topology-backup before every write.
pi      Symlinks hooks/pi/topology.ts from this repo into pi's extensions
        directory, so pulling the repo updates the extension.
goose   goose has no lifecycle hooks, so the session-start summary is written
        into .goosehints between BEGIN/END markers. It is a snapshot: re-run
        install after the topology or playbooks change.
"""

import json
import os
import shutil
import sys
from pathlib import Path

from .hooks import CLI, build_summary, load_playbooks_quietly, load_topology

HOOK_MARKER = 'topology.cli hook '
GOOSE_BEGIN = '<!-- topology:begin (generated by `topology hooks install --target goose`) -->'
GOOSE_END = '<!-- topology:end -->'
TARGETS = ('claude', 'pi', 'goose')
SCOPES = ('user', 'project')

REPO_ROOT = Path(__file__).resolve().parents[2]
PI_EXTENSION_SOURCE = REPO_ROOT / 'hooks' / 'pi' / 'topology.ts'


# ── Paths ────────────────────────────────────────────────────────────────────

def target_path(target: str, scope: str, cwd: Path | None = None, home: Path | None = None) -> Path:
    cwd = cwd or Path.cwd()
    home = home or Path.home()
    paths = {
        ('claude', 'user'): home / '.claude' / 'settings.json',
        ('claude', 'project'): cwd / '.claude' / 'settings.json',
        ('pi', 'user'): home / '.pi' / 'agent' / 'extensions' / 'topology.ts',
        ('pi', 'project'): cwd / '.pi' / 'extensions' / 'topology.ts',
        ('goose', 'user'): home / '.config' / 'goose' / '.goosehints',
        ('goose', 'project'): cwd / '.goosehints',
    }
    return paths[(target, scope)]


# ── Claude Code ──────────────────────────────────────────────────────────────

def claude_hook_entries() -> dict[str, dict]:
    return {
        'SessionStart': {'hooks': [{
            'type': 'command',
            'command': f'{CLI} hook session-start --format claude',
        }]},
        'UserPromptSubmit': {'hooks': [{
            'type': 'command',
            'command': f'{CLI} hook prompt --format claude',
            'timeout': 10,
        }]},
    }


def remove_claude_hooks(settings: dict) -> dict:
    """Drop every hook whose command contains HOOK_MARKER, pruning empty groups/events."""
    hooks = settings.get('hooks', {})
    for event in list(hooks):
        groups = []
        for group in hooks[event]:
            kept = [h for h in group.get('hooks', []) if HOOK_MARKER not in h.get('command', '')]
            if kept:
                groups.append({**group, 'hooks': kept})
        if groups:
            hooks[event] = groups
        else:
            del hooks[event]
    if 'hooks' in settings and not hooks:
        del settings['hooks']
    return settings


def add_claude_hooks(settings: dict) -> dict:
    settings = remove_claude_hooks(settings)
    hooks = settings.setdefault('hooks', {})
    for event, group in claude_hook_entries().items():
        hooks.setdefault(event, []).append(group)
    return settings


def claude_hooks_installed(settings: dict) -> bool:
    return any(
        HOOK_MARKER in h.get('command', '')
        for groups in settings.get('hooks', {}).values()
        for group in groups
        for h in group.get('hooks', [])
    )


def read_settings(path: Path) -> dict:
    if not path.exists():
        return {}
    text = path.read_text()
    return json.loads(text) if text.strip() else {}


def write_settings(path: Path, settings: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        shutil.copy2(path, path.with_name(path.name + '.topology-backup'))
    path.write_text(json.dumps(settings, indent=2) + '\n')


# ── goose ────────────────────────────────────────────────────────────────────

def build_goose_block(summary: str) -> str:
    body = summary or '[topology] No topology.toml found yet; run `topology init` first.'
    return '\n'.join([
        GOOSE_BEGIN,
        body,
        f'At the start of any task involving these machines, run `{CLI} hook session-start` '
        'for the current state, since this note is a snapshot.',
        GOOSE_END,
    ])


def strip_goose_block(text: str) -> str:
    start = text.find(GOOSE_BEGIN)
    end = text.find(GOOSE_END)
    if start == -1 or end == -1 or end < start:
        return text
    before = text[:start].rstrip('\n')
    after = text[end + len(GOOSE_END):].lstrip('\n')
    return '\n\n'.join(part for part in (before, after) if part)


def add_goose_block(text: str, block: str) -> str:
    rest = strip_goose_block(text).rstrip('\n')
    return (rest + '\n\n' + block if rest else block) + '\n'


# ── Actions ──────────────────────────────────────────────────────────────────

def install(target: str, path: Path) -> str:
    if target == 'claude':
        write_settings(path, add_claude_hooks(read_settings(path)))
        return f'claude: SessionStart and UserPromptSubmit hooks written to {path}'

    if target == 'pi':
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.is_symlink():
            path.unlink()
        elif path.exists():
            raise FileExistsError(f'{path} exists and is not a symlink; remove it first')
        path.symlink_to(PI_EXTENSION_SOURCE)
        return f'pi: {path} -> {PI_EXTENSION_SOURCE} (run /reload in an open pi session)'

    summary = build_summary(load_topology(), load_playbooks_quietly())
    path.parent.mkdir(parents=True, exist_ok=True)
    existing = path.read_text() if path.exists() else ''
    path.write_text(add_goose_block(existing, build_goose_block(summary)))
    return f'goose: topology block written to {path} (re-run after topology changes)'


def uninstall(target: str, path: Path) -> str:
    if target == 'claude':
        if not path.exists():
            return f'claude: {path} does not exist'
        write_settings(path, remove_claude_hooks(read_settings(path)))
        return f'claude: topology hooks removed from {path}'

    if target == 'pi':
        if path.is_symlink():
            path.unlink()
            return f'pi: removed {path}'
        return f'pi: no topology symlink at {path}'

    if not path.exists():
        return f'goose: {path} does not exist'
    path.write_text(strip_goose_block(path.read_text()).rstrip('\n') + '\n')
    return f'goose: topology block removed from {path}'


def is_installed(target: str, path: Path) -> bool:
    if target == 'claude':
        return path.exists() and claude_hooks_installed(read_settings(path))
    if target == 'pi':
        return path.is_symlink()
    return path.exists() and GOOSE_BEGIN in path.read_text()


# ── Entry point ──────────────────────────────────────────────────────────────

USAGE = ('usage: topology hooks install|uninstall --target claude|pi|goose [--scope user|project]\n'
         '       topology hooks status [--scope user|project]')


def parse_argv(argv: list[str]) -> tuple[str, str | None, str]:
    if not argv or argv[0] not in ('install', 'uninstall', 'status'):
        raise ValueError(USAGE)
    action, target, scope = argv[0], None, 'user'
    rest = argv[1:]
    while rest:
        flag, value, rest = rest[0], (rest[1] if len(rest) > 1 else None), rest[2:]
        if flag == '--target' and value in TARGETS:
            target = value
        elif flag == '--scope' and value in SCOPES:
            scope = value
        else:
            raise ValueError(USAGE)
    if action != 'status' and target is None:
        raise ValueError(USAGE)
    return action, target, scope


def main(argv: list[str]) -> None:
    try:
        action, target, scope = parse_argv(argv)
    except ValueError as e:
        print(e, file=sys.stderr)
        sys.exit(1)

    if action == 'status':
        for t in (target,) if target else TARGETS:
            path = target_path(t, scope)
            state = 'installed' if is_installed(t, path) else 'not installed'
            print(f'{t:7} {state:14} {path}')
        return

    path = target_path(target, scope)
    try:
        message = install(target, path) if action == 'install' else uninstall(target, path)
    except (OSError, json.JSONDecodeError) as e:
        print(f'{target}: {e}', file=sys.stderr)
        sys.exit(1)
    print(message)
